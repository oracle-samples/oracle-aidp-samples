"""The AIDP schemas a migration writes into, created before anything runs.

Every migrated table lives in an AIDP schema -- `default.SalesLake.claims_daily`
is table `claims_daily` in schema `SalesLake` in catalog `default` -- and AIDP
cannot write a table into a schema that does not exist. Nothing in this tool
used to create one. MEASURED on an AIDP cluster (Spark 3.5.0), 2026-09-30: the
demo's published `Daily_Claims` job failed at its first task with

    InvalidObjectException(message:There is no database hive.saleslake)

and, once the two schemas were created by hand, the same job ran green end to
end with the right data (issue #50). So this is the one step between the
migration's output and a job that runs.

Ported from the design on the unmerged `stack/7-runner-docs` line (`5bbacdc`):
a SQL script and a notebook carrying the same statements, every one
`IF NOT EXISTS`. That line had diverged from main by 99 commits and built names
through functions main no longer has, so this is a re-implementation of the
design rather than a cherry-pick. Two things differ from it, both on evidence:

* A schema name AIDP refuses is left OUT and listed, not emitted. AIDP's
  metastore accepts only `[a-z0-9_]` after folding case (see
  `naming.addressable`), and a refused `CREATE SCHEMA` raises. The old
  notebook ran its statements in one loop, so one hyphenated item name would
  have stopped every schema after it from being created.
* The notebook runs every statement and fails at the END, naming each one that
  failed, rather than stopping at the first.

MEASURED on an AIDP cluster (Spark 3.5.0), 2026-10-01, the generated output
itself: the bundled estate migrated with `--catalog <fresh name>` and
published, its job run twice.

    catalog before the run                 absent
    setup_catalogs task, run 1             SUCCESS; catalog + 3 schemas exist
    write 3 rows into a created schema     read back 3
    write into a schema nothing created    "There is no database"
    setup_catalogs task, run 2             SUCCESS (IF NOT EXISTS holds)

The downstream RunIngest failed both times on BucketNotFound -- the demo's
sample-data bucket does not exist there -- which is the input, not the setup.

And it is wired in, rather than left as a step to remember: `add_setup_task`
makes the setup notebook the first task of every migrated job, and `publish`
uploads it first. A first-time user whose job dies with "There is no database"
reads that as the tool failing, which is what it is.
"""
from __future__ import annotations

import json
from pathlib import Path

from fabric_aidp._atomic import write_text_atomic
from fabric_aidp.naming import (
    DEFAULT_CATALOG, addressable, aidp_schema, quote_part,
    unaddressable_schema_detail,
)

SETUP_DIR = "setup"
SETUP_SQL = f"{SETUP_DIR}/catalogs.sql"
SETUP_NOTEBOOK = f"{SETUP_DIR}/00_setup_catalogs.py"
SETUP_TASK_KEY = "setup_catalogs"

# The plan target types that carry an already-built AIDP schema in
# `target.schema`. Read rather than re-derived, so the setup script and the
# names the translators emit come from one place and cannot disagree.
_SCHEMA_BEARING = frozenset({
    "aidp_table", "aidp_view", "aidp_sql_object", "aidp_dcat_external_table",
})

_SQL_HEADER = """\
-- Generated by fabric-aidp-migrator. Creates every AIDP schema this migration
-- writes a table into. It must run before any migrated notebook, job,
-- Dataflow script or warehouse script: AIDP cannot write a table into a
-- schema that does not exist yet. Every statement is IF NOT EXISTS, so
-- running it again is harmless.
--
-- Every migrated job already runs this as its first task
-- (`00_setup_catalogs`). Run it yourself only for the scripts no job runs.
"""


def schema_targets(plan) -> dict:
    """{AIDP schema name: [where it comes from]} for every schema a migration names.

    Three sources:

    * a Lakehouse asset (`aidp_schema`): its schema is the item name;
    * a Warehouse object or shortcut table: `target.schema`, which the planner
      built with `naming.aidp_schema`;
    * a notebook's default-lakehouse binding: a write like
      `saveAsTable("x")` lands in that Lakehouse's schema, and the Lakehouse
      need not be in the export at all. In the bundled estate three of them
      are not: notebooks bound to `SomeLakehouse` and `casadinpadure`.

    Keyed on the name as built. AIDP folds case, so two spellings of one name
    are one schema; `setup_plan` collapses them. A collision between two
    *different* Fabric containers is the planner's NM01 finding, not this.
    """
    found: dict = {}

    def note(name, origin):
        name = str(name or "").strip()
        if name:
            found.setdefault(name, []).append(origin)

    assets = plan.get("assets") if isinstance(plan, dict) else None
    for asset in assets if isinstance(assets, list) else []:
        if not isinstance(asset, dict):
            continue
        target = asset.get("target") or {}
        source = asset.get("source") or {}
        kind = target.get("type")
        if kind == "aidp_schema":
            note(aidp_schema(target.get("name")), asset.get("id"))
        elif kind in _SCHEMA_BEARING:
            note(target.get("schema"), asset.get("id"))
        elif kind == "aidp_notebook" and source.get("default_lakehouse"):
            note(aidp_schema(source["default_lakehouse"]),
                 f"{asset.get('id')} (default lakehouse)")
    return found


def setup_plan(plan, aidp_catalog=DEFAULT_CATALOG) -> dict:
    """What the setup script creates, and what it cannot.

    `statements` is empty when there is nothing to create, and then no setup
    file is written and no job gets a setup task.

    No `CREATE CATALOG` for `default`: the AIDP `default` catalog exists on
    every cluster -- the demo job above ran after only its two SCHEMAS were
    created. Any other `--catalog` is created first. MEASURED on AIDP,
    2026-09-30: `CREATE CATALOG IF NOT EXISTS <name>` returns CREATED and the
    catalog shows in SHOW CATALOGS as INTERNAL.
    """
    catalog = str(aidp_catalog or DEFAULT_CATALOG).strip() or DEFAULT_CATALOG
    chosen, sources, refused = {}, {}, {}
    targets = schema_targets(plan)
    for name, origins in sorted(targets.items(), key=lambda kv: kv[0].casefold()):
        folded = name.casefold()
        if not addressable(name):
            refused.setdefault(name, []).extend(origins)
            continue
        # First spelling wins; AIDP stores the folded form either way.
        chosen.setdefault(folded, name)
        sources.setdefault(folded, []).extend(origins)
    statements = []
    if catalog.casefold() != DEFAULT_CATALOG:
        statements.append(f"CREATE CATALOG IF NOT EXISTS {quote_part(catalog)}")
    statements += [
        f"CREATE SCHEMA IF NOT EXISTS {quote_part(catalog)}.{quote_part(name)}"
        for name in chosen.values()]
    if not chosen:
        statements = []
    return {
        "catalog": catalog,
        "schemas": list(chosen.values()),
        "refused": [{"schema": name, "from": sorted(set(origins))}
                    for name, origins in sorted(refused.items())],
        "statements": statements,
    }


def _notebook_source(statements) -> str:
    star = "*" * 20
    listed = "\n".join(f"    {s!r}," for s in statements)
    return (
        f"# Fabric notebook source\n\n"
        f"# MARKDOWN {star}\n\n"
        f"# # Create the AIDP schemas this migration writes into\n"
        f"# Generated by fabric-aidp-migrator. Every migrated job runs this as\n"
        f"# its first task, because AIDP cannot write a table into a schema that\n"
        f"# does not exist. Every statement is IF NOT EXISTS, so it is safe to\n"
        f"# run any number of times.\n\n"
        f"# CELL {star}\n\n"
        f"STATEMENTS = [\n{listed}\n]\n\n"
        f"# Every statement runs; the cell fails at the end if any did. Stopping\n"
        f"# at the first failure would leave every schema after it uncreated,\n"
        f"# and the jobs depending on them would fail later and less clearly.\n"
        f"failed = []\n"
        f"for statement in STATEMENTS:\n"
        f"    try:\n"
        f"        spark.sql(statement)\n"
        f"        print('ok    ', statement)\n"
        f"    except Exception as exc:  # report every failure, then fail\n"
        f"        failed.append((statement, exc))\n"
        f"        print('FAILED', statement, '--', exc)\n"
        f"if failed:\n"
        f"    raise RuntimeError(\n"
        f"        f'{{len(failed)}} of {{len(STATEMENTS)}} setup statement(s) failed: '\n"
        f"        + '; '.join(f'{{s}} ({{e}})' for s, e in failed))\n")


def write_setup(out_dir, setup: dict) -> dict:
    """Write the setup script and notebook; the `report["setup"]` entry.

    Nothing is written when there is nothing to create. The refused schemas
    are reported either way: they are the reason some table cannot exist.
    """
    out_dir = Path(out_dir)
    entry = {"catalog": setup["catalog"], "schemas": setup["schemas"],
             "refused": setup["refused"], "statements": len(setup["statements"]),
             "sql": None, "notebook": None}
    if not setup["statements"]:
        return entry
    write_text_atomic(out_dir / SETUP_SQL, _SQL_HEADER + "".join(
        f"{statement};\n" for statement in setup["statements"]))
    write_text_atomic(out_dir / SETUP_NOTEBOOK,
                      _notebook_source(setup["statements"]))
    entry["sql"], entry["notebook"] = SETUP_SQL, SETUP_NOTEBOOK
    return entry


def setup_task_path(workspace_prefix: str) -> str:
    """The notebookPath a job task uses for the setup notebook.

    The same shape `migrate` writes for every other task, so `publish`
    resolves it with the same lookup.
    """
    return f"{workspace_prefix}/{Path(SETUP_NOTEBOOK).name}"


def add_setup_task(job_json: str, notebook_path: str) -> str:
    """The job with the setup notebook as its first task.

    Every task that depended on nothing now depends on the setup task, so no
    task can reach a write before the schemas exist, and a failed setup stops
    the job at its first task with the reason in the output -- not three
    tasks later as "There is no database".

    The task key is `setup_catalogs`, or the first `setup_catalogs_<n>` the
    job does not already use: a Fabric activity may be called anything.
    """
    payload = json.loads(job_json)
    tasks = payload.get("tasks")
    if not isinstance(tasks, list) or not tasks:
        return job_json
    used = {t.get("taskKey") for t in tasks if isinstance(t, dict)}
    key, n = SETUP_TASK_KEY, 2
    while key in used:
        key, n = f"{SETUP_TASK_KEY}_{n}", n + 1
    for task in tasks:
        if isinstance(task, dict) and not task.get("dependsOn"):
            task["dependsOn"] = [{"taskKey": key}]
    tasks.insert(0, {
        "type": "NOTEBOOK_TASK",
        "taskKey": key,
        "runIf": "ALL_SUCCESS",
        "maxRetries": 0,
        "notebookPath": notebook_path,
        "source": "WORKSPACE",
        "timeoutSeconds": 3600,
    })
    ending = "\n" if job_json.endswith("\n") else ""
    return json.dumps(payload, indent=2) + ending


def lakehouse_row(asset: dict, setup_entry: dict) -> dict:
    """A Lakehouse asset's report row: its schema, created by the setup script.

    It used to fall through to `planned -- no translator for this asset type`,
    which `verify` shows as SKIP and the RUNBOOK explains as expected. That
    hid exactly the step a first run fails on.
    """
    source = asset.get("source") or {}
    name = source.get("name") or (asset.get("target") or {}).get("name") or "?"
    schema = aidp_schema(name)
    catalog = setup_entry.get("catalog") or DEFAULT_CATALOG
    if not addressable(schema):
        return {"asset_id": asset["id"], "kind": "lakehouse",
                "status": "needs_manual_review", "changes": 0, "flags": 1,
                "findings": [{
                    "rule": "LH02_SCHEMA_NOT_ADDRESSABLE",
                    "detail": (f"Lakehouse {name!r} is not in the setup script. "
                               + unaddressable_schema_detail([schema])),
                    "severity": "flag"}]}
    return {"asset_id": asset["id"], "kind": "lakehouse", "status": "ok",
            "changes": 1, "flags": 0,
            "output_path": setup_entry.get("sql"),
            "findings": [{
                "rule": "LH01_SCHEMA_IN_SETUP",
                "detail": (f"Lakehouse {name!r} -> AIDP schema "
                           f"{quote_part(catalog)}.{quote_part(schema)}, created "
                           f"by {SETUP_SQL} and by the {Path(SETUP_NOTEBOOK).stem} "
                           f"notebook, which every migrated job runs as its "
                           f"first task. Its tables are not migrated here: a "
                           f"Fabric Git export carries no Lakehouse data"),
                "severity": "rewrite"}]}
